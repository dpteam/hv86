<#
.SYNOPSIS
    Draws the hv86 icon and writes assets\hv86.ico + PNG previews.

.DESCRIPTION
    The mark: a stack of three isometric plates (a host and its VMs) in cold
    blue on a dark tile - readable down to 16 px, and unmistakably "a pile of
    machines", which is what a hypervisor is.

    Everything is generated by GDI+, so the icon is reproducible and can be
    tweaked without binary assets in the repository.

    Output:
      assets\hv86.ico              multi-size icon (16..256, PNG-compressed)
      assets\hv86-256.png           previews
      assets\hv86-64.png
      assets\hv86-32.png
      assets\hv86-16.png
      assets\icon-preview.png       contact sheet for review

    NOTE: keep this file ASCII-only (see fetch-webview2.ps1).
    NOTE: use [Type]::new(...) rather than New-Object Type(...) - the latter
          silently turns parenthesised argument lists into arrays.
#>
[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing

$root      = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)
$assetsDir = Join-Path $root 'assets'

if (-not (Test-Path $assetsDir)) { New-Item -ItemType Directory -Path $assetsDir -Force | Out-Null }

function New-IconBitmap([int]$size) {
    $S = [single]$size
    $bmp = [System.Drawing.Bitmap]::new($size, $size, [System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
    $g = [System.Drawing.Graphics]::FromImage($bmp)

    $g.SmoothingMode = [System.Drawing.Drawing2D.SmoothingMode]::AntiAlias
    $g.InterpolationMode = [System.Drawing.Drawing2D.InterpolationMode]::HighQualityBicubic
    $g.PixelOffsetMode = [System.Drawing.Drawing2D.PixelOffsetMode]::HighQuality
    $g.CompositingQuality = [System.Drawing.Drawing2D.CompositingQuality]::HighQuality
    $g.Clear([System.Drawing.Color]::Transparent)

    # ---- tile
    $pad = $S * 0.045
    $inner = $S - 2 * $pad
    $rect = [System.Drawing.RectangleF]::new($pad, $pad, $inner, $inner)
    $radius = $S * 0.235
    $d = $radius * 2

    $tile = [System.Drawing.Drawing2D.GraphicsPath]::new()
    $tile.AddArc($rect.X, $rect.Y, $d, $d, 180, 90)
    $tile.AddArc(($rect.Right - $d), $rect.Y, $d, $d, 270, 90)
    $tile.AddArc(($rect.Right - $d), ($rect.Bottom - $d), $d, $d, 0, 90)
    $tile.AddArc($rect.X, ($rect.Bottom - $d), $d, $d, 90, 90)
    $tile.CloseFigure()

    $bg = [System.Drawing.Drawing2D.LinearGradientBrush]::new(
        $rect,
        [System.Drawing.Color]::FromArgb(255, 0x16, 0x1F, 0x2B),
        [System.Drawing.Color]::FromArgb(255, 0x05, 0x08, 0x0C),
        [single]90.0)
    $g.FillPath($bg, $tile)

    # ---- soft glow under the stack
    $g.SetClip($tile)
    $glowRect = [System.Drawing.RectangleF]::new(($S * 0.02), ($S * 0.10), ($S * 0.96), ($S * 0.96))
    $glowPath = [System.Drawing.Drawing2D.GraphicsPath]::new()
    $glowPath.AddEllipse($glowRect)
    $glow = [System.Drawing.Drawing2D.PathGradientBrush]::new($glowPath)
    $glow.CenterColor = [System.Drawing.Color]::FromArgb(110, 0x2B, 0x7F, 0xD4)
    $glow.SurroundColors = @([System.Drawing.Color]::FromArgb(0, 0x2B, 0x7F, 0xD4))
    $g.FillPath($glow, $glowPath)
    $g.ResetClip()

    # ---- the stack
    $w = $S * 0.615
    $h = $w * 0.50
    $thickness = $S * 0.068
    $cx = $S * 0.5
    $centers = @(($S * 0.335), ($S * 0.505), ($S * 0.675))

    $colorTop = @(
        [System.Drawing.Color]::FromArgb(255, 0x8A, 0xDD, 0xFF),
        [System.Drawing.Color]::FromArgb(255, 0x56, 0xB2, 0xF6),
        [System.Drawing.Color]::FromArgb(255, 0x33, 0x84, 0xC6))
    $colorBottom = @(
        [System.Drawing.Color]::FromArgb(255, 0x37, 0x9D, 0xEE),
        [System.Drawing.Color]::FromArgb(255, 0x27, 0x79, 0xCC),
        [System.Drawing.Color]::FromArgb(255, 0x16, 0x50, 0x85))

    $sideColor = [System.Drawing.Color]::FromArgb(255, 0x07, 0x24, 0x3D)
    $topLight = [System.Drawing.Color]::FromArgb(235, 0xD6, 0xF4, 0xFF)
    $innerLine = [System.Drawing.Color]::FromArgb(110, 0xFF, 0xFF, 0xFF)

    for ($i = 2; $i -ge 0; $i--) {
        $cy = $centers[$i]

        # plate thickness: a dark diamond shifted down
        $sy = $cy + $thickness
        $side = [System.Drawing.Drawing2D.GraphicsPath]::new()
        $side.AddPolygon(@(
            [System.Drawing.PointF]::new($cx, ($sy - $h / 2)),
            [System.Drawing.PointF]::new(($cx + $w / 2), $sy),
            [System.Drawing.PointF]::new($cx, ($sy + $h / 2)),
            [System.Drawing.PointF]::new(($cx - $w / 2), $sy)))
        $sideBrush = [System.Drawing.SolidBrush]::new($sideColor)
        $g.FillPath($sideBrush, $side)

        # the plate itself
        $plate = [System.Drawing.Drawing2D.GraphicsPath]::new()
        $plate.AddPolygon(@(
            [System.Drawing.PointF]::new($cx, ($cy - $h / 2)),
            [System.Drawing.PointF]::new(($cx + $w / 2), $cy),
            [System.Drawing.PointF]::new($cx, ($cy + $h / 2)),
            [System.Drawing.PointF]::new(($cx - $w / 2), $cy)))

        $plateRect = [System.Drawing.RectangleF]::new(($cx - $w / 2), ($cy - $h / 2), $w, $h)
        $brush = [System.Drawing.Drawing2D.LinearGradientBrush]::new($plateRect, $colorTop[$i], $colorBottom[$i], [single]55.0)
        $g.FillPath($brush, $plate)

        # bevel: light catches the back edges, which makes the plate read as a
        # solid object rather than a flat diamond
        if ($size -ge 24) {
            $bevelPen = [System.Drawing.Pen]::new([System.Drawing.Color]::FromArgb(90, 0xFF, 0xFF, 0xFF),
                [single][Math]::Max(1.0, $S * 0.005))
            $g.DrawLines($bevelPen, @(
                [System.Drawing.PointF]::new(($cx - $w / 2), $cy),
                [System.Drawing.PointF]::new($cx, ($cy - $h / 2)),
                [System.Drawing.PointF]::new(($cx + $w / 2), $cy)))
            $bevelPen.Dispose()
        }

        if ($i -eq 0) {
            $penWidth = [single][Math]::Max(1.0, $S * 0.008)
            $pen = [System.Drawing.Pen]::new($topLight, $penWidth)
            $g.DrawPath($pen, $plate)

            # "screen" inside the top plate: a nested diamond
            if ($size -ge 48) {
                $k = 0.46
                $innerDiamond = [System.Drawing.Drawing2D.GraphicsPath]::new()
                $innerDiamond.AddPolygon(@(
                    [System.Drawing.PointF]::new($cx, ($cy - $h * $k / 2)),
                    [System.Drawing.PointF]::new(($cx + $w * $k / 2), $cy),
                    [System.Drawing.PointF]::new($cx, ($cy + $h * $k / 2)),
                    [System.Drawing.PointF]::new(($cx - $w * $k / 2), $cy)))
                $innerPen = [System.Drawing.Pen]::new($innerLine, [single][Math]::Max(1.0, $S * 0.006))
                $g.DrawPath($innerPen, $innerDiamond)
                $innerPen.Dispose()
                $innerDiamond.Dispose()
            }

            $pen.Dispose()
        }

        $brush.Dispose()
        $plate.Dispose()
        $sideBrush.Dispose()
        $side.Dispose()
    }

    # ---- tile border
    $borderWidth = [single][Math]::Max(1.0, $S * 0.010)
    $border = [System.Drawing.Pen]::new([System.Drawing.Color]::FromArgb(150, 0x3A, 0x55, 0x74), $borderWidth)
    $g.DrawPath($border, $tile)

    $border.Dispose()
    $bg.Dispose()
    $glow.Dispose()
    $glowPath.Dispose()
    $tile.Dispose()
    $g.Dispose()

    return $bmp
}

# ---------------------------------------------------------------- render

$sizes = @(16, 20, 24, 32, 40, 48, 64, 128, 256)
$tempDir = Join-Path ([System.IO.Path]::GetTempPath()) ("hv86-icon-" + [Guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $tempDir -Force | Out-Null

$images = New-Object System.Collections.ArrayList

foreach ($size in $sizes) {
    $bmp = New-IconBitmap $size
    $file = Join-Path $tempDir ("icon-{0}.png" -f $size)
    $bmp.Save($file, [System.Drawing.Imaging.ImageFormat]::Png)
    $bmp.Dispose()

    [void]$images.Add([System.IO.File]::ReadAllBytes($file))
    Write-Host ("  rendered {0}x{0}" -f $size)
}

# ---------------------------------------------------------------- ICO

$icoPath = Join-Path $assetsDir 'hv86.ico'
$stream = [System.IO.MemoryStream]::new()
$writer = [System.IO.BinaryWriter]::new($stream)

$writer.Write([UInt16]0)                 # reserved
$writer.Write([UInt16]1)                 # type: icon
$writer.Write([UInt16]$sizes.Count)      # image count

$offset = 6 + 16 * $sizes.Count

for ($i = 0; $i -lt $sizes.Count; $i++) {
    $size = $sizes[$i]
    $data = [byte[]]$images[$i]
    $dim = 0
    if ($size -lt 256) { $dim = $size }

    $writer.Write([Byte]$dim)
    $writer.Write([Byte]$dim)
    $writer.Write([Byte]0)               # palette
    $writer.Write([Byte]0)               # reserved
    $writer.Write([UInt16]1)             # planes
    $writer.Write([UInt16]32)            # bpp
    $writer.Write([UInt32]$data.Length)
    $writer.Write([UInt32]$offset)

    $offset += $data.Length
}

foreach ($data in $images) {
    $bytes = [byte[]]$data
    $writer.Write($bytes, 0, $bytes.Length)
}

$writer.Flush()
[System.IO.File]::WriteAllBytes($icoPath, $stream.ToArray())
$writer.Dispose()
$stream.Dispose()

Write-Host ("icon: {0} ({1} bytes, {2} sizes)" -f $icoPath, (Get-Item $icoPath).Length, $sizes.Count)

# ---------------------------------------------------------------- previews

foreach ($size in @(256, 64, 32, 16)) {
    $index = $sizes.IndexOf($size)
    [System.IO.File]::WriteAllBytes((Join-Path $assetsDir ("hv86-{0}.png" -f $size)), [byte[]]$images[$index])
}

$sheet = [System.Drawing.Bitmap]::new(430, 300, [System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
$sg = [System.Drawing.Graphics]::FromImage($sheet)
$sg.SmoothingMode = [System.Drawing.Drawing2D.SmoothingMode]::AntiAlias
$sg.Clear([System.Drawing.Color]::FromArgb(255, 0x0C, 0x0F, 0x14))

$big = New-IconBitmap 256
$sg.DrawImage($big, 16, 22, 256, 256)
$big.Dispose()

$font = [System.Drawing.Font]::new('Consolas', 10)
$textBrush = [System.Drawing.SolidBrush]::new([System.Drawing.Color]::FromArgb(255, 0x6F, 0x81, 0x99))
$y = 24

foreach ($size in @(64, 48, 32, 24, 16)) {
    $small = New-IconBitmap $size
    $sg.DrawImage($small, 292, $y, $size, $size)
    $sg.DrawString(("{0}px" -f $size), $font, $textBrush, (292 + $size + 12), ($y + [Math]::Max(0, ($size - 14) / 2)))
    $small.Dispose()
    $y += $size + 12
}

$textBrush.Dispose()
$font.Dispose()
$sg.Dispose()
$sheet.Save((Join-Path $assetsDir 'icon-preview.png'), [System.Drawing.Imaging.ImageFormat]::Png)
$sheet.Dispose()

Remove-Item $tempDir -Recurse -Force -ErrorAction SilentlyContinue

Write-Host "preview: assets\icon-preview.png"
exit 0